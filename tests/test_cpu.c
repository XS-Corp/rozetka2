    CHECK(42,0x48,0x81,0xec,8,2,0,0,0x48,0x0f,0xae,4,0x24,0xc6,0x44,0x24,4,1,0x48,0x0f,0xae,0x0c,0x24,
        0x48,0x81,0xc4,8,2,0,0,0xb8,42,0,0,0,0xc3);
    const uint8_t unaligned[]={0x48,0x81,0xec,0,2,0,0,0x48,0x0f,0xae,4,0x24,0xc3};
